/// Root app: MaterialApp with global text scale, and AppRoot that picks the
/// initial screen depending on whether a database is loaded.
library;

import 'package:material_ui/material_ui.dart';

import 'package:pandive/core/services/share_file.dart';
import 'package:pandive/l10n/app_localizations.dart';
import 'app_root.dart';
import 'settings/settings.dart';
import 'theme/app_theme.dart';

class PandiveApp extends StatelessWidget {
  final Settings settings;
  const PandiveApp({super.key, required this.settings});

  @override
  Widget build(BuildContext context) {
    return AnimatedBuilder(
      animation: settings,
      builder: (context, _) {
        return MaterialApp(
          title: 'PanDive',
          debugShowCheckedModeBanner: false,
          scaffoldMessengerKey: appMessengerKey,
          theme: appTheme(Brightness.light),
          darkTheme: appTheme(Brightness.dark),
          themeMode: settings.themeMode,
          locale: settings.locale, // null = system language
          // The globals must be the material_ui ones (this SDK's Material
          // is a fork with its own MaterialLocalizations). The
          // flutter_localizations ones generated by gen-l10n are another type: they
          // leave MaterialLocalizations.of == null in every non-English language and
          // the chrome (NavigationBar/FAB/drawer) breaks (grey boxes).
          localizationsDelegates: const [
            AppLocalizations.delegate,
            ...GlobalMaterialLocalizations.delegates,
          ],
          supportedLocales: AppLocalizations.supportedLocales,
          builder: (context, child) {
            // Global text scale (accessibility / presbyopia).
            final mq = MediaQuery.of(context);
            return MediaQuery(
              data: mq.copyWith(
                textScaler: TextScaler.linear(settings.textScale),
              ),
              child: child!,
            );
          },
          home: AppRoot(settings: settings),
        );
      },
    );
  }
}
